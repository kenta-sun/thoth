-- ============================================================
-- 记忆正文版本表
-- ============================================================

CREATE TABLE memory_version
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    memory_id      BIGINT      NOT NULL,
    content        TEXT        NOT NULL,
    version_status CHAR(1)     NOT NULL DEFAULT 'A',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(128),
    updated_by     VARCHAR(128),
    CONSTRAINT fk_memory_version_memory
        FOREIGN KEY (memory_id)
            REFERENCES memory (id)
            ON DELETE CASCADE
);

-- 创建索引
CREATE INDEX idx_memory_version_memory_id ON memory_version (memory_id);
-- 创建混合语种倒排索引
CREATE INDEX idx_memory_version_content_pgroonga ON memory_version USING pgroonga (content);

COMMENT ON TABLE memory_version IS '记忆正文版本表';

COMMENT ON COLUMN memory_version.id IS 'ID，自增主键';
COMMENT ON COLUMN memory_version.memory_id IS '记忆单元ID';
COMMENT ON COLUMN memory_version.content IS '记忆正文';
COMMENT ON COLUMN memory_version.version_status IS '记忆正文版本的状态';
COMMENT ON COLUMN memory_version.created_at IS '创建时间';
COMMENT ON COLUMN memory_version.updated_at IS '最后更新时间';
COMMENT ON COLUMN memory_version.created_by IS '创建者';
COMMENT ON COLUMN memory_version.updated_by IS '最后修改者';
