-- 用户由使用者手动通过 SQL 维护，MCP 仅查询。
CREATE TABLE user_tbl
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(128) COLLATE "C" NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(128) DEFAULT CURRENT_USER,
    updated_by     VARCHAR(128) DEFAULT CURRENT_USER,
    CONSTRAINT uk_user_tbl_username UNIQUE (username),
    -- 空白集合与 Python str.strip 一致，禁止空用户名和首尾 Unicode 空白。
    CONSTRAINT ck_user_tbl_username CHECK (
        char_length(username) > 0 AND username = btrim(username, U&'\0009\000A\000B\000C\000D\001C\001D\001E\001F\0020\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\2028\2029\202F\205F\3000')
    )
);
COMMENT ON TABLE user_tbl IS '手动维护的用户表，不包含登录认证信息';
COMMENT ON COLUMN user_tbl.id IS '用户ID，数据库生成的主键';
COMMENT ON COLUMN user_tbl.username IS '唯一用户名，最多128字符，按原文区分大小写且无首尾空白';
COMMENT ON COLUMN user_tbl.created_at IS '创建时间';
COMMENT ON COLUMN user_tbl.updated_at IS '最后更新时间';
COMMENT ON COLUMN user_tbl.created_by IS '创建者';
COMMENT ON COLUMN user_tbl.updated_by IS '最后修改者';
