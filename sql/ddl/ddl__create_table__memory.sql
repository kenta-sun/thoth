-- ============================================================
-- 记忆单元表
-- ============================================================

CREATE TABLE memory
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    embedding      VECTOR(1536) NOT NULL,
    summary        VARCHAR(128) NOT NULL,
    current_status CHAR(1)      NOT NULL DEFAULT 'A',
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(128),
    updated_by     VARCHAR(128)
);

-- 创建 HNSW 索引
CREATE INDEX idx_memory_embedding_hnsw ON memory USING hnsw (embedding vector_cosine_ops);

COMMENT ON TABLE memory IS '记忆单元表';

COMMENT ON COLUMN memory.id IS 'ID，自增主键';
COMMENT ON COLUMN memory.embedding IS '记忆摘要对应的向量数据，用于向量相似度检索';
COMMENT ON COLUMN memory.summary IS '记忆摘要';
COMMENT ON COLUMN memory.current_status IS '当前状态，与最新的记忆正文状态相同';
COMMENT ON COLUMN memory.created_at IS '创建时间';
COMMENT ON COLUMN memory.updated_at IS '最后更新时间';
COMMENT ON COLUMN memory.created_by IS '创建者';
COMMENT ON COLUMN memory.updated_by IS '最后修改者';
