-- ============================================================
-- 单词表
-- 前置表：word_sts_tbl
-- ============================================================

CREATE TABLE word_tbl
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word           TEXT        NOT NULL,
    common_form    TEXT        NOT NULL,
    hiragana       TEXT        NOT NULL,
    meaning        TEXT        NOT NULL,
    status_code    CHAR(1)     NOT NULL DEFAULT 'A',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(128) DEFAULT CURRENT_USER,
    updated_by     VARCHAR(128) DEFAULT CURRENT_USER,
    CONSTRAINT uk_word_tbl_word UNIQUE (word),
    CONSTRAINT fk_word_tbl_word_sts_tbl
        FOREIGN KEY (status_code)
            REFERENCES word_sts_tbl (code)
);

COMMENT ON TABLE word_tbl IS '单词表';

COMMENT ON COLUMN word_tbl.id IS '单词ID，自增主键';
COMMENT ON COLUMN word_tbl.word IS '单词基本形式，唯一，用于判重和更新定位，包含已删除单词';
COMMENT ON COLUMN word_tbl.common_form IS '单词常用写法，新增时未提供则由程序使用基本形式填入';
COMMENT ON COLUMN word_tbl.hiragana IS '平假名读音';
COMMENT ON COLUMN word_tbl.meaning IS '中文释义';
COMMENT ON COLUMN word_tbl.status_code IS '单词状态，A=正在使用，D=被删除';
COMMENT ON COLUMN word_tbl.created_at IS '创建时间';
COMMENT ON COLUMN word_tbl.updated_at IS '最后更新时间';
COMMENT ON COLUMN word_tbl.created_by IS '创建者';
COMMENT ON COLUMN word_tbl.updated_by IS '最后修改者';
