SUMMARIZE_SYSTEM = """你是一个记忆摘要生成器。你会收到一条已经精炼好的记忆正文，需要为它生成一条摘要，并判断这条记忆是否过于散乱。

# 摘要要求
1. **长度硬上限 {max_chars} 个字符**，超出即为不合格。宁可短，不要超。
2. 摘要要能独立描述这条记忆的核心含义，信息密度尽量高。将来它会被向量化用于语义检索，也会作为判重的唯一依据，所以必须准确抓住这条记忆「讲的是什么」。
3. 使用陈述句，不要加书名号、引号、编号或「摘要：」这类前缀。
4. 只能使用正文中已有的信息，不允许臆造。
5. 用中文输出。

# 散乱判定
如果这条正文同时涵盖多个互不相关的主题，导致你无法用一句话概括它的核心含义，就把 `needs_resplit` 置为 true，并在 `resplit_reason` 中说明它混合了哪几个主题。这种情况说明上游拆分得不好，需要重新拆分。

判定要克制：只有真正混合了**互不相关**主题时才置 true。同一件事的多个细节、同一属性的多个限定条件都不算散乱。

`needs_resplit` 为 false 时，`resplit_reason` 返回空字符串。

即使判定为散乱，也仍然要尽力给出一条摘要。"""


def build_summarize_system(max_chars: int) -> str:
    """
    构造摘要阶段的系统提示词。

    入参：
    - max_chars : 摘要的最大字符数。
    返回：
    - 已填入长度上限的系统提示词。
      长度上限来自配置而非写死，是为了和 memory.summary 的列宽约束联动。
    """
    return SUMMARIZE_SYSTEM.format(max_chars=max_chars)


def build_summarize_user(refined_content: str) -> str:
    """
    构造摘要阶段的用户消息。

    入参：
    - refined_content : 精炼后的记忆正文。
    返回：
    - 用户消息字符串。
    """
    return f"请为下面这条记忆正文生成摘要。\n\n<记忆正文>\n{refined_content}\n</记忆正文>"


def build_summarize_retry_user(
    refined_content: str,
    previous_summary: str,
    max_chars: int,
) -> str:
    """
    构造摘要重试的用户消息。

    首次生成的摘要超长时使用。把上一次的失败结果和超出的字符数一并告知模型，
    比单纯重试一次的成功率高得多。

    入参：
    - refined_content  : 精炼后的记忆正文。
    - previous_summary : 上一次生成的、超长的摘要。
    - max_chars        : 摘要的最大字符数。
    返回：
    - 用户消息字符串。
    """
    return (
        f"你上一次生成的摘要有 {len(previous_summary)} 个字符，"
        f"超过了 {max_chars} 个字符的上限，不合格。\n\n"
        f"<上一次的摘要>\n{previous_summary}\n</上一次的摘要>\n\n"
        f"请重新生成一条不超过 {max_chars} 个字符的摘要，保留最核心的语义，砍掉次要修饰。\n\n"
        f"<记忆正文>\n{refined_content}\n</记忆正文>"
    )


