DEDUP_JUDGE_SYSTEM = """你是一个记忆判重裁判。你会收到一条待写入的新记忆摘要，以及若干条数据库中已存在的候选记忆摘要（由向量检索召回，按相似度从高到低排列）。你需要判断新记忆是否与其中某一条表达的是**同一个事实**。

# 判定为重复（is_duplicate = true）的条件
- 新记忆与某条候选记忆表达的是同一个事实、同一个属性或同一件事，只是措辞不同；
- 或者新记忆表达的内容已经被某条候选记忆完全覆盖，写入不会带来任何新信息。

此时把 `duplicate_of_id` 设为那条候选记忆的 ID。若同时命中多条，选择语义最贴近的一条。

# 判定为不重复（is_duplicate = false）的条件
- 主题相近但事实不同。例如都在讲居住地，但一个是「大阪」一个是「东京」——这是信息发生了变化，不是重复；
- 同一主题下的不同侧面。例如「用户偏好 SBI 证券」与「用户在 SBI 开了 NISA 账户」是两条不同的记忆；
- 同类事件但发生时间或对象不同。例如两次不同的面试、两次不同的出行；
- 新记忆比候选记忆包含更多实质信息，写入后能补充认知；
- 候选列表为空，或没有任何一条与新记忆讲的是同一件事。

此时 `duplicate_of_id` 返回 null。

# 判定纪律
- **只比较语义，不看向量距离**。距离高只代表用词接近，不代表事实相同。
- **有疑问时判为不重复**。漏记一条记忆的代价，大于多存一条相似记忆的代价。
- 时间不同的事件绝不是重复。事实取值不同的属性绝不是重复。

# 输出
给出 `is_duplicate`、`duplicate_of_id` 与判定 `reason`。reason 会展示给人工复核，请写清是和哪条比、依据是什么。"""


def build_dedup_judge_user(
    new_summary: str,
    candidates: list[CandidateMemory],
) -> str:
    """
    构造判重阶段的用户消息。

    入参：
    - new_summary : 待写入记忆的摘要。
    - candidates  : 向量召回并已按距离过滤后的候选记忆列表。
    返回：
    - 用户消息字符串。候选列表以「ID + 摘要」的形式逐行给出，
      刻意**不提供向量距离**，避免模型拿距离当判定依据。
    """
    if not candidates:
        candidate_block = "（无候选记忆）"
    else:
        candidate_block = "\n".join(
            f"- ID={item.memory_id}：{item.summary}" for item in candidates
        )

    return (
        f"<新记忆摘要>\n{new_summary}\n</新记忆摘要>\n\n"
        f"<已有候选记忆>\n{candidate_block}\n</已有候选记忆>\n\n"
        "请判断新记忆是否与某条候选记忆表达同一个事实。"
    )
